#!/usr/bin/env bash
# Regenerate scripts/proxy/litellm-requirements.lock: a --require-hashes
# lock of litellm[proxy,extra-proxy]==<pin> for the gateway box
# (Ubuntu 24.04 arm64, CPython 3.12, wheels only).
#
# Run on any machine with network access to pypi.org (read-only; nothing
# is installed). The resolve happens with pip's cross-platform dry-run
# resolver, so an x86 build host can lock for aarch64.
#
# NEVER pin 1.82.7 or 1.82.8 (malicious PyPI releases, March 2026
# supply-chain compromise of the litellm publishing pipeline).
set -euo pipefail

LITELLM_VERSION="${LITELLM_VERSION:-1.106.2}"
case "$LITELLM_VERSION" in
  1.82.7|1.82.8)
    echo "REFUSING: litellm $LITELLM_VERSION is a known-malicious release." >&2
    exit 1
    ;;
esac

INFRA_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${INFRA_DIR}/scripts/proxy/litellm-requirements.lock"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

python3 -m pip install --quiet --dry-run --ignore-installed \
  --report "$WORK/report.json" \
  --python-version 312 \
  --platform manylinux_2_28_aarch64 \
  --platform manylinux2014_aarch64 \
  --platform linux_aarch64 \
  --platform any \
  --implementation cp \
  --abi cp312 --abi abi3 --abi none \
  --only-binary :all: \
  --target "$WORK/resolve" \
  "litellm[proxy,extra-proxy]==${LITELLM_VERSION}"

python3 - "$WORK/report.json" "$OUT" "$LITELLM_VERSION" <<'PYEOF'
import json, sys
report = json.load(open(sys.argv[1]))
lines = [
    f"# litellm[proxy,extra-proxy]=={sys.argv[3]} hash lock for the harness2-eval gateway",
    "# Target: Ubuntu 24.04 arm64 (t4g.small), CPython 3.12, wheels only.",
    "# Generated by dev/regen-litellm-lock.sh (pip dry-run --report; nothing installed).",
    "# Install on the proxy with:",
    "#   pip install --require-hashes -r litellm-requirements.lock",
    "# NEVER use litellm 1.82.7 or 1.82.8 (malicious releases, March 2026).",
    "",
]
pkgs = {}
for item in report["install"]:
    meta = item["metadata"]
    name, version = meta["name"], meta["version"]
    sha = item["download_info"]["archive_info"]["hashes"]["sha256"]
    pkgs[name] = (version, sha)
for name in sorted(pkgs, key=str.lower):
    version, sha = pkgs[name]
    lines.append(f"{name}=={version} \\")
    lines.append(f"    --hash=sha256:{sha}")
open(sys.argv[2], "w").write("\n".join(lines) + "\n")
print(f"wrote {sys.argv[2]} with {len(pkgs)} pinned packages")
PYEOF
